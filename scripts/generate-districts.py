"""Build the atlas's SVG districts from pinned geoBoundaries / OSM data.

Derived geometry: ODbL 1.0. See data/districts.LICENSE.md.
Run from the repository root: python3 scripts/generate-districts.py
"""
import json
from pathlib import Path
from urllib.request import urlopen

SOURCE = 'https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/LKA/ADM2/geoBoundaries-LKA-ADM2_simplified.geojson'


def project_ring(ring):
    points = []
    for lon, lat, *_ in ring:
        point = f'{(lon - 79.4) * 165:.1f},{(10.05 - lat) * 165:.1f}'
        if not points or point != points[-1]:
            points.append(point)
    return 'M' + 'L'.join(points) + 'Z'


def generate(data):
    rows = []
    for feature in data['features']:
        name = feature['properties']['shapeName'].removesuffix(' District')
        geometry = feature['geometry']
        polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
        path = ''.join(project_ring(ring) for polygon in polygons for ring in polygon)
        rows.append({'id': name.lower().replace(' ', '-'), 'name': name, 'path': path})
    header = '// GENERATED by scripts/generate-districts.py — do not edit geometry by hand.\n'
    header += '// © OpenStreetMap contributors, via geoBoundaries. ODbL 1.0; see districts.LICENSE.md.\n'
    header += '// Administrative districts, source year 2017; projected to the atlas coordinate system.\n\n'
    Path('data/districts.ts').write_text(header + 'export const districts = ' + json.dumps(rows, indent=2) + ' as const\n')


if __name__ == '__main__':
    with urlopen(SOURCE) as response:
        generate(json.load(response))
